#!/usr/bin/env python3
"""Merge the stage outputs into results.json and results.md. Every number in results.md comes from results.json."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"
ev, tr, ds, tm = (json.load(open(R / f)) for f in ("eval.json", "train_stats.json", "data_stats.json", "timing.json"))
curve = [json.loads(l) for l in open(R / "train_log.jsonl")]; curve = [r for r in curve if "val500_syllable_accuracy" in r and r["step"] % 3000 == 0]
ex = json.load(open(R / "examples.json")); errs = json.load(open(R / "top_errors.json"))

PRICE_SOURCE = "https://www.runpod.io/pricing"
PRICE_DATE = "2026-10-16"
PRICES = {"runpod_rtx4090_community_usd_per_h": 0.34, "runpod_rtx4090_secure_usd_per_h": 0.89}

gpu_s = tm["train_seconds_wall_incl_load"] + tm["eval_seconds_wall_incl_load"]
pipeline_s = tm["total_seconds"]   # run.sh timer around the whole pipeline
cost = {"is_estimate": True, "price_source": PRICE_SOURCE, "price_date": PRICE_DATE, "prices": PRICES,
        "gpu_hours": gpu_s / 3600, "pipeline_hours_incl_setup_and_data": pipeline_s / 3600}
for k, p in PRICES.items():
    cost[k.replace("_usd_per_h", "") + "_gpu_only_usd"] = gpu_s / 3600 * p
    cost[k.replace("_usd_per_h", "") + "_whole_pipeline_usd"] = pipeline_s / 3600 * p
res = {"task": "Vietnamese diacritics restoration (ASCII text in, diacritised text out)",
       "model": {"name": "google/canine-s", "revision": "75d6d0b3f4d0bffed0ca7ddd0b73949977d4ca02", "licence": "Apache-2.0"},
       "dataset": {**ds["source"], "licence": "CC BY-SA (3.0 on the Hugging Face snapshot) + GFDL"},
       "data": {"articles_in_shard": ds["articles"], "used_sentences": ds["used_sentences"], "used_articles": ds["used_articles"]},
       "training": tr, "systems": ev["systems"], "inference": ev["inference"], "base_letters_changed": ev["base_letters_changed"],
       "timing": tm, "gpu_seconds": gpu_s, "peak_vram_gb_train": tr["peak_vram_allocated_gb"], "cost_estimate": cost}
json.dump(res, open(ROOT / "results.json", "w"), indent=1)

S = ev["systems"]
def pct(x): return f"{100 * x:.2f}"
def ci(c): return f"[{pct(c[0])}, {pct(c[1])}]"
names = [("copy_input", "Baseline A: copy the input (no diacritics)"),
         ("unigram_lookup", "Baseline B: most frequent form of each syllable seen in training"),
         ("canine_before_finetune", "CANINE-s before fine-tuning (random head)"),
         ("canine_finetuned", "CANINE-s fine-tuned (ours)")]
L = ["# Results", "", "Generated by `scripts/make_results.py` from `results/*.json`; machine-readable copy in `results.json`.",
     f"Test set: {ev['test_sentences']} sentences from {ds['used_articles']['test']} Wikipedia articles that are not in the training set (split by article).", "",
     "## Test-set accuracy (higher is better)", "",
     "| System | Letter acc. % | Letter acc. 95% CI | Syllable acc. % | Syllable acc. 95% CI | Unseen-syllable acc. % | Sentence exact match % |", "|---|---|---|---|---|---|---|"]
for k, n in names:
    s = S[k]
    L.append(f"| {n} | {pct(s['letter_accuracy'])} | {ci(s['letter_accuracy_ci95'])} | {pct(s['syllable_accuracy'])} | {ci(s['syllable_accuracy_ci95'])} | {pct(s['unseen_syllable_accuracy'])} | {pct(s['sentence_accuracy'])} |")
f, b = S["canine_finetuned"], S["unigram_lookup"]
L += ["", f"Counts: {f['letters']} letters, {f['syllables']} syllables ({f['unseen_syllables']} not seen in training) in the test set. "
      "Unseen syllables are mostly foreign words and names that carry no diacritics, which is why even the copy baseline scores 90% there; it is a small, easy slice and not a measure of generalisation. "
      "CIs are sentence-level bootstrap, 1000 resamples, seed 1234. Letter accuracy counts every alphabetic character, including those that carry no diacritic, "
      "so the copy baseline is not zero.",
      f"Fine-tuned vs the unigram baseline: syllable error rate {pct(b['syllable_error_rate'])}% to {pct(f['syllable_error_rate'])}%.",
      f"Base letters changed by the model: {ev['base_letters_changed']} (checked on every test sentence by an assertion; it cannot happen by construction).", "",
      "## Validation curve (first 500 validation sentences, syllable accuracy; the test set is not used during training)", "",
      "| Step | " + " | ".join(str(r["step"]) for r in curve) + " |", "|---|" + "---|" * len(curve),
      "| Val-500 syllable acc. % | " + " | ".join(pct(r["val500_syllable_accuracy"]) for r in curve) + " |", "",
      "## Compute", "",
      "| Item | Value |", "|---|---|",
      f"| GPU | {tr['gpu']} (shared with other jobs; only our process counted for VRAM) |",
      f"| Training | {tr['steps']} steps, batch {tr['batch_size']}, {tr['epochs']} epochs over {tr['train_sentences']} sentences, lr {tr['lr']}, bf16 autocast |",
      f"| Training time (in-process) | {tr['train_seconds'] / 60:.1f} min |",
      f"| GPU wall time, train + eval incl. model loading | {gpu_s / 3600:.2f} GPU-hours ({gpu_s / 60:.1f} min) |",
      f"| Peak VRAM during training (torch allocated / reserved) | {tr['peak_vram_allocated_gb']:.2f} / {tr['peak_vram_reserved_gb']:.2f} GB |",
      f"| Peak VRAM during test inference (allocated) | {ev['inference']['peak_vram_allocated_gb']:.2f} GB |",
      f"| Inference speed on the test set | {ev['inference']['sentences_per_second']:.0f} sentences/s (batch 128) |",
      f"| Data preparation (CPU, 290 MB download already cached; `run.sh` timer, `results/timing.json`) | {tm['data_seconds']:.0f} s |",
      f"| Setup (pinned installs; venv already present, so a cold install is not timed) | {tm['setup_seconds']:.2f} s |",
      f"| Whole pipeline wall time (`run.sh` total, `results/timing.json`) | {pipeline_s / 60:.1f} min |", "",
      "## Cost if rented (estimate)", "",
      f"Hourly prices read from {PRICE_SOURCE} on {PRICE_DATE} (page marked as updated 2026-10-08): RTX 4090 Community Cloud ${PRICES['runpod_rtx4090_community_usd_per_h']}/h, Secure Cloud ${PRICES['runpod_rtx4090_secure_usd_per_h']}/h. "
      "Prices change; this is an estimate, not an invoice. We ran on our own card and paid nothing for GPU time.", "",
      "| Scope | Community | Secure |", "|---|---|---|",
      f"| GPU time only ({cost['gpu_hours']:.2f} h) | ${cost['runpod_rtx4090_community_gpu_only_usd']:.2f} | ${cost['runpod_rtx4090_secure_gpu_only_usd']:.2f} |",
      f"| Whole pipeline (`run.sh` total, incl. data prep, venv already installed) ({cost['pipeline_hours_incl_setup_and_data']:.2f} h) | ${cost['runpod_rtx4090_community_whole_pipeline_usd']:.2f} | ${cost['runpod_rtx4090_secure_whole_pipeline_usd']:.2f} |", "",
      "## Examples from the test set", "",
      "Text excerpts are from Vietnamese Wikipedia (article title given), CC BY-SA / GFDL, authors listed in each article's history. Input is the gold sentence with diacritics removed.", ""]
def block(title, items):
    L.extend([f"### {title}", ""])
    for e in items:
        L.extend([f"- Article: *{e['title']}*", f"  - Input: `{e['input']}`", f"  - Gold: {e['gold']}",
                  f"  - Baseline B: {e['unigram_lookup']}", f"  - Fine-tuned: {e['finetuned']}"])
    L.append("")
block("Fine-tuned model right, baseline B wrong (first 5 of a seeded shuffle)", ex["model_right_baseline_wrong"])
block("Model wrong (first 8 of the same shuffle, not cherry-picked)", ex["model_wrong"])
L += ["### Most frequent syllable errors of the fine-tuned model", "", "| Gold | Predicted | Count |", "|---|---|---|"]
L += [f"| {e['gold']} | {e['predicted']} | {e['count']} |" for e in errs[:15]]
open(ROOT / "results.md", "w").write("\n".join(L) + "\n")
print("\n".join(L[:20]))
